// ========== SUBMIT REVIEW ==========
async function submitReview() {
    const rating = selectedRating;
    const name = document.getElementById('reviewName').value.trim();
    const comment = document.getElementById('reviewComment').value.trim();
    
    if (rating === 0) {
        alert('Silakan pilih rating bintang terlebih dahulu!');
        return;
    }
    if (!comment) {
        alert('Silakan tulis komentar!');
        return;
    }
    
    const btn = event.target;
    btn.disabled = true;
    btn.innerHTML = '<i class="fas fa-spinner fa-pulse"></i> Mengirim...';
    
    try {
        const response = await fetch('api/submit-review.php', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ rating, name: name || 'Anonymous', comment })
        });
        const data = await response.json();
        
        if (data.success) {
            alert('Terima kasih atas review-nya!');
            location.reload();
        } else {
            alert('Gagal mengirim review: ' + data.message);
        }
    } catch (error) {
        alert('Gagal mengirim review: ' + error.message);
    } finally {
        btn.disabled = false;
        btn.innerHTML = '<i class="fas fa-paper-plane"></i> Kirim Review';
    }
}

